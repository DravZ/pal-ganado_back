package com.palavaca.back.service;

import com.palavaca.back.dto.InvestmentDTO;
import com.palavaca.back.model.Animal;
import com.palavaca.back.model.CostAllocation;
import com.palavaca.back.model.Expense;
import com.palavaca.back.model.FeedingRecord;
import com.palavaca.back.repository.AnimalRepository;
import com.palavaca.back.repository.CostAllocationRepository;
import com.palavaca.back.repository.ExpenseRepository;
import com.palavaca.back.repository.FeedingRecordRepository;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.math.BigDecimal;
import java.math.RoundingMode;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.UUID;

/**
 * Calcula el dinero invertido en cada animal, lote y finca.
 *
 * Inversión por animal = costo de adquisición
 *   + costos asignados directamente al animal
 *   + parte proporcional de los costos asignados a su lote
 *   + alimentación (directa, de lote o de finca, prorrateada)
 *   + parte proporcional de los gastos de finca aún no asignados.
 *
 * Para no contar dos veces: los gastos de alimentación y de adquisición de animal se
 * excluyen del prorrateo general (su costo ya entra por alimentación y costo de
 * adquisición), y de cada gasto solo se prorratea lo que no está asignado.
 */
@Service
@RequiredArgsConstructor
public class InvestmentService {

    private final AnimalRepository animalRepository;
    private final CostAllocationRepository costAllocationRepository;
    private final ExpenseRepository expenseRepository;
    private final FeedingRecordRepository feedingRecordRepository;

    @Transactional(readOnly = true)
    public InvestmentDTO.FarmInvestment summarizeFarm(UUID farmId) {
        List<Animal> activeAnimals = animalRepository.findByFarmId(farmId).stream()
                .filter(animal -> animal.getStatus() == null || "active".equalsIgnoreCase(animal.getStatus()))
                .toList();
        int activeCount = activeAnimals.size();

        List<CostAllocation> allocations = costAllocationRepository.findByFarmIdOrderByAllocationDateDesc(farmId);
        List<Expense> expenses = expenseRepository.findByFarmIdOrderByExpenseDateDesc(farmId);
        List<FeedingRecord> feedings = feedingRecordRepository.findByFarmIdOrderByFeedingDateDesc(farmId);

        Map<UUID, Integer> animalsByLot = new HashMap<>();
        for (Animal animal : activeAnimals) {
            if (animal.getLot() != null) {
                animalsByLot.merge(animal.getLot().getId(), 1, Integer::sum);
            }
        }

        Map<UUID, BigDecimal> allocatedByExpense = new HashMap<>();
        for (CostAllocation allocation : allocations) {
            if (allocation.getExpense() != null) {
                allocatedByExpense.merge(allocation.getExpense().getId(), amount(allocation.getAmount()), BigDecimal::add);
            }
        }

        BigDecimal unassignedFarmTotal = BigDecimal.ZERO;
        for (Expense expense : expenses) {
            if (isAutoGeneratedCost(expense.getReferenceType())) continue;
            BigDecimal unassigned = amount(expense.getAmount())
                    .subtract(allocatedByExpense.getOrDefault(expense.getId(), BigDecimal.ZERO));
            if (unassigned.signum() > 0) {
                unassignedFarmTotal = unassignedFarmTotal.add(unassigned);
            }
        }

        Map<UUID, BigDecimal> feedingByAnimal = new HashMap<>();
        Map<UUID, BigDecimal> feedingByLot = new HashMap<>();
        BigDecimal farmLevelFeeding = BigDecimal.ZERO;
        for (FeedingRecord feeding : feedings) {
            BigDecimal cost = amount(feeding.getCost());
            if (feeding.getAnimal() != null) {
                feedingByAnimal.merge(feeding.getAnimal().getId(), cost, BigDecimal::add);
            } else if (feeding.getLot() != null) {
                feedingByLot.merge(feeding.getLot().getId(), cost, BigDecimal::add);
            } else {
                farmLevelFeeding = farmLevelFeeding.add(cost);
            }
        }

        Map<UUID, BigDecimal> allocationByAnimal = new HashMap<>();
        Map<UUID, BigDecimal> allocationByLot = new HashMap<>();
        for (CostAllocation allocation : allocations) {
            if (allocation.getExpense() != null && isAutoGeneratedCost(allocation.getExpense().getReferenceType())) {
                continue;
            }
            if (allocation.getAnimal() != null) {
                allocationByAnimal.merge(allocation.getAnimal().getId(), amount(allocation.getAmount()), BigDecimal::add);
            } else if (allocation.getLot() != null) {
                allocationByLot.merge(allocation.getLot().getId(), amount(allocation.getAmount()), BigDecimal::add);
            }
        }

        BigDecimal overheadPerAnimal = split(unassignedFarmTotal, activeCount);
        BigDecimal farmFeedingPerAnimal = split(farmLevelFeeding, activeCount);

        List<InvestmentDTO.AnimalInvestment> results = new ArrayList<>();
        BigDecimal farmTotal = BigDecimal.ZERO;
        for (Animal animal : activeAnimals) {
            BigDecimal acquisition = amount(animal.getAcquisitionCost());
            BigDecimal assigned = allocationByAnimal.getOrDefault(animal.getId(), BigDecimal.ZERO);

            BigDecimal lotAssigned = BigDecimal.ZERO;
            BigDecimal lotFeeding = BigDecimal.ZERO;
            UUID lotId = null;
            String lotName = null;
            if (animal.getLot() != null) {
                lotId = animal.getLot().getId();
                lotName = animal.getLot().getName();
                int lotCount = Math.max(animalsByLot.getOrDefault(lotId, 1), 1);
                lotAssigned = split(allocationByLot.getOrDefault(lotId, BigDecimal.ZERO), lotCount);
                lotFeeding = split(feedingByLot.getOrDefault(lotId, BigDecimal.ZERO), lotCount);
            }

            BigDecimal feeding = feedingByAnimal.getOrDefault(animal.getId(), BigDecimal.ZERO)
                    .add(lotFeeding)
                    .add(farmFeedingPerAnimal);

            BigDecimal animalTotal = acquisition
                    .add(assigned)
                    .add(lotAssigned)
                    .add(feeding)
                    .add(overheadPerAnimal)
                    .setScale(2, RoundingMode.HALF_UP);
            farmTotal = farmTotal.add(animalTotal);

            results.add(new InvestmentDTO.AnimalInvestment(
                    animal.getId(),
                    animal.getTagNumber(),
                    animal.getName(),
                    lotId,
                    lotName,
                    acquisition.setScale(2, RoundingMode.HALF_UP),
                    assigned.add(lotAssigned).setScale(2, RoundingMode.HALF_UP),
                    feeding.setScale(2, RoundingMode.HALF_UP),
                    overheadPerAnimal.setScale(2, RoundingMode.HALF_UP),
                    animalTotal,
                    animalTotal));
        }

        BigDecimal average = activeCount > 0
                ? farmTotal.divide(BigDecimal.valueOf(activeCount), 2, RoundingMode.HALF_UP)
                : BigDecimal.ZERO;
        return new InvestmentDTO.FarmInvestment(
                farmId, activeCount, farmTotal.setScale(2, RoundingMode.HALF_UP), average, results);
    }

    private boolean isAutoGeneratedCost(String referenceType) {
        return FinanceIntegrationService.REFERENCE_FEEDING.equals(referenceType)
                || FinanceIntegrationService.REFERENCE_ANIMAL.equals(referenceType);
    }

    private BigDecimal amount(BigDecimal value) {
        return value == null ? BigDecimal.ZERO : value;
    }

    private BigDecimal split(BigDecimal total, int divisor) {
        if (divisor <= 0 || total == null || total.signum() == 0) return BigDecimal.ZERO;
        return total.divide(BigDecimal.valueOf(divisor), 2, RoundingMode.HALF_UP);
    }
}
